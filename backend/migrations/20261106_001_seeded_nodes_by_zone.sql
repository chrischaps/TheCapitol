--
--   tree in rural 426, fallen_branches in rural 256 and suburban 72,
--   rock_outcrop in rural 103, iron_vein in rural 9,
--   clay_bank in urban 42 and suburban 36
--
-- Their resource types come from backend/content, which startup syncs after
-- the migrations run, so the rows can't go into resource_nodes yet (its
